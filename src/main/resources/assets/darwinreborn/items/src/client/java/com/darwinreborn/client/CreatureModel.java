package com.darwinreborn.client;

import com.darwinreborn.DarwinReborn;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.util.Mth;

/**
 * One model that contains every body part variant; the genes decide which variants are visible.
 * Dimensions are {width, height, depth} in model pixels. Index 0 of an appendage means "absent".
 */
public final class CreatureModel extends EntityModel<CreatureRenderState> {

    public static final ModelLayerLocation LAYER = new ModelLayerLocation(DarwinReborn.id("creature"), "main");

    // Box sizes and texture origins come from AtlasLayout (generated by tools/make_assets.py, which also paints the textures).
    private static final int[][] BODY = AtlasLayout.BODY;
    private static final int[][] HEAD = AtlasLayout.HEAD;
    private static final int[][] SNOUT = AtlasLayout.SNOUT;
    private static final int[][] EAR = AtlasLayout.EAR;
    private static final int[][] TAIL = AtlasLayout.TAIL;
    private static final int[][] LEG = AtlasLayout.LEG;
    private static final int[][] CREST = AtlasLayout.CREST;

    private static final float BASE_LEG = 6.0f;

    private final ModelPart bodyPivot;
    private final ModelPart headPivot;
    private final ModelPart[] bodies = new ModelPart[4];
    private final ModelPart[] heads = new ModelPart[4];
    private final ModelPart[] snouts = new ModelPart[4];
    private final ModelPart[] earsL = new ModelPart[4];
    private final ModelPart[] earsR = new ModelPart[4];
    private final ModelPart[] tails = new ModelPart[4];
    private final ModelPart[] crests = new ModelPart[4];
    /** [pair 0 = rear, 1 = front][shape][side 0 = left, 1 = right] */
    private final ModelPart[][][] legs = new ModelPart[2][4][2];

    public CreatureModel(ModelPart root) {
        super(root);
        bodyPivot = root.getChild("body_pivot");
        headPivot = bodyPivot.getChild("head_pivot");
        for (int s = 0; s < 4; s++) {
            bodies[s] = bodyPivot.getChild("body_" + s);
            if (s == 0) continue;
            tails[s] = bodyPivot.getChild("tail_" + s);
            crests[s] = bodyPivot.getChild("crest_" + s);
            heads[s] = headPivot.getChild("head_" + s);
            snouts[s] = headPivot.getChild("snout_" + s);
            earsL[s] = headPivot.getChild("ear_l_" + s);
            earsR[s] = headPivot.getChild("ear_r_" + s);
            for (int pair = 0; pair < 2; pair++) {
                legs[pair][s][0] = root.getChild(legName(pair, s, 0));
                legs[pair][s][1] = root.getChild(legName(pair, s, 1));
            }
        }
    }

    private static String legName(int pair, int shape, int side) {
        return (pair == 0 ? "rear" : "front") + "_leg_" + shape + (side == 0 ? "_l" : "_r");
    }

    public static LayerDefinition createLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();

        PartDefinition bodyPivot = root.addOrReplaceChild("body_pivot", CubeListBuilder.create(), PartPose.offset(0, 15, 0));
        PartDefinition headPivot = bodyPivot.addOrReplaceChild("head_pivot", CubeListBuilder.create(), PartPose.ZERO);

        for (int s = 0; s < 4; s++) {
            int[] b = BODY[s];
            bodyPivot.addOrReplaceChild("body_" + s,
                    CubeListBuilder.create().texOffs(AtlasLayout.BODY_UV[s][0], AtlasLayout.BODY_UV[s][1])
                            .addBox(-b[0] / 2f, -b[1] / 2f, -b[2] / 2f, b[0], b[1], b[2]),
                    PartPose.ZERO);
            if (s == 0) continue;

            int[] t = TAIL[s];
            bodyPivot.addOrReplaceChild("tail_" + s,
                    CubeListBuilder.create().texOffs(AtlasLayout.TAIL_UV[s][0], AtlasLayout.TAIL_UV[s][1])
                            .addBox(-t[0] / 2f, -t[1] / 2f, 0, t[0], t[1], t[2]),
                    PartPose.ZERO);

            // crest: 1 = three spikes along the back, 2 = a sail, 3 = a mane. Boxes rise from the part's origin upwards.
            int[] c = CREST[s];
            CubeListBuilder crest = CubeListBuilder.create().texOffs(AtlasLayout.CREST_UV[s][0], AtlasLayout.CREST_UV[s][1]);
            if (s == 1) {
                for (float z : new float[] {-4.0f, -1.0f, 2.0f}) {
                    crest.addBox(-c[0] / 2f, -c[1], z, c[0], c[1], c[2]);
                }
            } else {
                crest.addBox(-c[0] / 2f, -c[1], -c[2] / 2f, c[0], c[1], c[2]);
            }
            bodyPivot.addOrReplaceChild("crest_" + s, crest, PartPose.ZERO);

            int[] h = HEAD[s];
            headPivot.addOrReplaceChild("head_" + s,
                    CubeListBuilder.create().texOffs(AtlasLayout.HEAD_UV[s][0], AtlasLayout.HEAD_UV[s][1])
                            .addBox(-h[0] / 2f, -h[1] / 2f, -h[2], h[0], h[1], h[2]),
                    PartPose.ZERO);

            int[] n = SNOUT[s];
            headPivot.addOrReplaceChild("snout_" + s,
                    CubeListBuilder.create().texOffs(AtlasLayout.SNOUT_UV[s][0], AtlasLayout.SNOUT_UV[s][1])
                            .addBox(-n[0] / 2f, -n[1] / 2f, -n[2], n[0], n[1], n[2]),
                    PartPose.ZERO);

            int[] e = EAR[s];
            CubeListBuilder ear = CubeListBuilder.create().texOffs(AtlasLayout.EAR_UV[s][0], AtlasLayout.EAR_UV[s][1])
                    .addBox(-e[0] / 2f, -e[1], -e[2] / 2f, e[0], e[1], e[2]);
            headPivot.addOrReplaceChild("ear_l_" + s, ear, PartPose.ZERO);
            headPivot.addOrReplaceChild("ear_r_" + s, ear, PartPose.ZERO);

            int[] l = LEG[s];
            CubeListBuilder leg = CubeListBuilder.create().texOffs(AtlasLayout.LEG_UV[s][0], AtlasLayout.LEG_UV[s][1])
                    .addBox(-l[0] / 2f, 0, -l[2] / 2f, l[0], l[1], l[2]);
            for (int pair = 0; pair < 2; pair++) {
                root.addOrReplaceChild(legName(pair, s, 0), leg, PartPose.ZERO);
                root.addOrReplaceChild(legName(pair, s, 1), leg, PartPose.ZERO);
            }
        }
        return LayerDefinition.create(mesh, AtlasLayout.WIDTH, AtlasLayout.HEIGHT);
    }

    @Override
    public void setupAnim(CreatureRenderState state) {
        super.setupAnim(state);

        int bodyShape = clamp(state.body);
        int[] body = BODY[bodyShape];
        boolean hasLegs = state.rearLegs > 0 || state.frontLegs > 0;
        float legScale = 0.6f + 0.9f * state.legLength;
        float hipY = hasLegs ? 24.0f - BASE_LEG * legScale : 24.0f;

        // ---- body ----
        for (int s = 0; s < 4; s++) bodies[s].visible = s == bodyShape;
        bodyPivot.y = hipY - body[1] / 2f + (hasLegs ? 1.0f : 0.0f);
        bodyPivot.xRot = -state.tiltDegrees * 0.6f * Mth.DEG_TO_RAD;

        // ---- head, snout, ears (all hang off the head pivot, so they turn together) ----
        int headShape = clamp(state.head);
        float headW = headShape > 0 ? HEAD[headShape][0] : 5.0f;
        float headH = headShape > 0 ? HEAD[headShape][1] : 4.0f;
        float headD = headShape > 0 ? HEAD[headShape][2] : 0.0f;
        headPivot.setPos(0, -body[1] / 2f + 2.5f, -body[2] / 2f);
        headPivot.xRot = state.xRot * Mth.DEG_TO_RAD;
        headPivot.yRot = state.yRot * Mth.DEG_TO_RAD;

        int snoutShape = clamp(state.snout);
        int earShape = clamp(state.ears);
        for (int s = 1; s < 4; s++) {
            heads[s].visible = s == headShape;
            snouts[s].visible = s == snoutShape;
            snouts[s].setPos(0, 0, -headD);
            earsL[s].visible = s == earShape;
            earsR[s].visible = s == earShape;
            float earX = headW / 2 - 0.5f;
            earsL[s].setPos(-earX, -headH / 2, -Math.max(headD / 2, 1.0f));
            earsR[s].setPos(earX, -headH / 2, -Math.max(headD / 2, 1.0f));
            float tilt = s == 2 ? 0.7f : s == 3 ? 0.35f : 0.0f;   // floppy ears and horns lean outwards
            earsL[s].zRot = -tilt;
            earsR[s].zRot = tilt;
        }

        // ---- tail ----
        int tailShape = clamp(state.tail);
        float wag = Mth.sin(state.ageInTicks * 0.3f) * 0.3f;
        for (int s = 1; s < 4; s++) {
            tails[s].visible = s == tailShape;
            tails[s].setPos(0, -body[1] / 2f + 2.0f, body[2] / 2f);
            tails[s].yRot = wag;
        }

        // ---- crest ----
        int crestShape = clamp(state.crest);
        for (int s = 1; s < 4; s++) {
            crests[s].visible = s == crestShape;
            float z = s == 3 ? -body[2] / 2f + 2.5f : 0.0f;       // the mane sits on the neck
            crests[s].setPos(0, -body[1] / 2f + 0.6f, z);
        }

        // ---- legs ----
        float swing = Mth.cos(state.walkAnimationPos * 0.6662f) * 1.4f * state.walkAnimationSpeed;
        float legX = Math.max(1.0f, body[0] / 2f - 1.0f);
        for (int pair = 0; pair < 2; pair++) {
            int shape = clamp(pair == 0 ? state.rearLegs : state.frontLegs);
            float z = pair == 0 ? body[2] / 2f - 2.0f : -body[2] / 2f + 2.0f;
            for (int s = 1; s < 4; s++) {
                for (int side = 0; side < 2; side++) {
                    ModelPart leg = legs[pair][s][side];
                    leg.visible = s == shape;
                    leg.setPos(side == 0 ? -legX : legX, hipY, z);
                    leg.yScale = legScale;
                    boolean sameDiagonal = (pair == 0) == (side == 0);
                    leg.xRot = sameDiagonal ? swing : -swing;
                }
            }
        }
    }

    private static int clamp(int shape) {
        return Math.max(0, Math.min(3, shape));
    }
}
