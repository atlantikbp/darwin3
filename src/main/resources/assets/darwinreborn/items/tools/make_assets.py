# ---------- creature textures (128x128 atlas, see tools/atlas.py) ----------
#   creature_base_C.png     neutral grey coat of type C (smooth, fur, scales, fluffy), tinted by the primary colour gene
#   mark_N.png              markings of pattern N on transparent ground, tinted by the marking colour gene (also the crest)
#   eyes_{white,iris,shine,closed}_S.png   the layers of eye shape S on the head faces; closed = eyelid while blinking
import atlas
from atlas import PARTS, UV, ATLAS_W, ATLAS_H

for f in os.listdir(f"{ROOT}/textures/entity"):
    os.remove(f"{ROOT}/textures/entity/{f}")

def new_img(rgba): return Image.new("RGBA", (ATLAS_W, ATLAS_H), (0, 0, 0, 0) if rgba else (255, 255, 255, 255))

def each_box():
    for kind, shapes in PARTS.items():
        for shape, dims in enumerate(shapes):
            if dims:
                u0, v0 = UV[(kind, shape)]
                yield kind, shape, dims, u0, v0

for coat in range(4):
    base = new_img(True)
    bp = base.load()
    for kind, shape, (w, h, d), u0, v0 in each_box():
        for u, v, X, Y, Z, face in atlas.texels(u0, v0, w, h, d):
            g = atlas.base_grey(kind, coat, X, Y, Z, w, h, d, face)
            bp[u, v] = (g, g, g, 255)
    base.save(f"{ROOT}/textures/entity/creature_base_{coat}.png")

for pat in range(12):
    img = new_img(True); px = img.load()
    for kind, shape, (w, h, d), u0, v0 in each_box():
        seed = shape * 7 + len(kind)
        for u, v, X, Y, Z, face in atlas.texels(u0, v0, w, h, d):
            g = atlas.mark_grey(pat, kind, X, Y, Z, w, h, d, seed)
            if g is not None:
                px[u, v] = (g, g, g, 255)
    img.save(f"{ROOT}/textures/entity/mark_{pat}.png")

# eyes: four textures per shape, drawn as separate layers: white (sclera), iris+pupil, shine (highlight), closed (blink)
for shp in range(4):
    layers = {k: new_img(True) for k in ("white", "iris", "shine", "closed")}
    px = {k: im.load() for k, im in layers.items()}
    rows = atlas.EYE_SHAPES[shp][0]
    for head_shape in (1, 2, 3):
        w, h, d = PARTS["head"][head_shape]
        u0, v0 = UV[("head", head_shape)]
        lay = atlas.eye_layout(shp, w, h)
        for x, y in lay["white"]:  px["white"][u0 + d + x, v0 + d + y] = (255, 255, 255, 255)
        for x, y, g in lay["iris"]: px["iris"][u0 + d + x, v0 + d + y] = (g, g, g, 255)
        for x, y in lay["shine"]:  px["shine"][u0 + d + x, v0 + d + y] = (255, 255, 255, 255)
        for x, y in lay["closed"]: px["closed"][u0 + d + x, v0 + d + y] = (255, 255, 255, 255)
        # a smaller eye on each side face, one pixel behind the front edge
        if d >= 3:
            y = lay["iris"][0][1]
            for sx in (u0 + d - 2, u0 + d + w + 1):
                px["iris"][sx, v0 + d + y] = (atlas.IRIS_GREY["I"],) * 3 + (255,)
                px["closed"][sx, v0 + d + y] = (255, 255, 255, 255)
    for k, im in layers.items():
        im.save(f"{ROOT}/textures/entity/eyes_{k}_{shp}.png")

# Java side of the atlas: the model reads dimensions and UV origins from here, so both stay in sync
def jarr(vals):
    return "null" if vals is None else "{" + ", ".join(str(x) for x in vals) + "}"
lines = ["package com.darwinreborn.client;", "", "/** GENERATED by tools/make_assets.py. Do not edit by hand. */",
         "final class AtlasLayout {", f"    static final int WIDTH = {ATLAS_W};", f"    static final int HEIGHT = {ATLAS_H};", ""]
for kind, shapes in PARTS.items():
    lines.append(f"    /** {{width, height, depth}} per shape, null = absent */")
    lines.append(f"    static final int[][] {kind.upper()} = {{" + ", ".join(jarr(x) for x in shapes) + "};")
    lines.append(f"    /** {{u, v}} per shape */")
    lines.append(f"    static final int[][] {kind.upper()}_UV = {{" + ", ".join(jarr(UV.get((kind, i))) for i in range(len(shapes))) + "};")
lines += ["", "    private AtlasLayout() {}", "}", ""]
open("src/client/java/com/darwinreborn/client/AtlasLayout.java", "w").write("\n".join(lines))

# ---------- item textures (16x16, drawn with simple shapes) ----------
def item_lens():
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0)); p = img.load()
    for y in range(16):
        for x in range(16):
            d = ((x - 6.5) ** 2 + (y - 6.5) ** 2) ** 0.5
            if d <= 5.5:
                p[x, y] = (120, 60, 160, 255) if d > 4.2 else (170, 230, 220, 200)
    for k in range(5):                           # handle
        p[10 + k, 10 + k] = (110, 80, 50, 255); p[11 + k, 10 + k] = (80, 55, 35, 255) if 11 + k < 16 else (0, 0, 0, 0)
    img.save(f"{ROOT}/textures/item/genetic_lens.png")

def item_egg():
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0)); p = img.load()
    for y in range(16):
        for x in range(16):
            if ((x - 7.5) / 5.0) ** 2 + ((y - 8.5) / 6.5) ** 2 <= 1:
                p[x, y] = (230, 215, 150, 255)
                if (x + y) % 5 == 0: p[x, y] = (150, 110, 170, 255)
    img.save(f"{ROOT}/textures/item/creature_spawn_egg.png")
item_lens(); item_egg()

for name in ("genetic_lens", "creature_spawn_egg"):
    json.dump({"model": {"type": "minecraft:model", "model": f"darwinreborn:item/{name}"}}, open(f"{ROOT}/items/{name}.json", "w"), indent=2)
    json.dump({"parent": "minecraft:item/generated", "textures": {"layer0": f"darwinreborn:item/{name}"}}, open(f"{ROOT}/models/item/{name}.json", "w"), indent=2)

